#!/usr/bin/env bash
# End-to-end check of infill patterns a build leaves out (CMake options ORCA_INFILL_<NAME>=OFF).
#
# A process preset naming a left-out pattern still loads and slices. The CLI warns that the pattern
# is not included, lists an "infill_pattern_unavailable" warning in result.json, and prints the same
# G-code as with the pattern's fallback. Only the option's line in the config block tells them apart.
#
# usage: test_cli_infill_unavailable.sh <orca-slicer binary> <python3> <left-out CMake names, ';'-separated>
set -u

BIN="${1:-}"
PY="${2:-python3}"
LEFT_OUT="${3:-}"
# 77 is the test's SKIP_RETURN_CODE.
[ -x "$BIN" ] || { echo "SKIP: orca-slicer binary not found: $BIN"; exit 77; }
[ -n "$LEFT_OUT" ] || { echo "SKIP: this build includes every infill pattern"; exit 77; }

MODEL="$(cd "$(dirname "$0")/../data" && pwd)/20mm_cube.obj"

# CMake name, token, fallback token and slots of each built-in pattern a build may leave out
# (src/libslic3r/Fill/Modules/<name>/).
PATTERNS="
ZIGZAG           zigzag            rectilinear       sparse
CROSSZAG         crosszag          rectilinear       sparse
LOCKEDZAG        lockedzag         rectilinear       sparse
LINE             line              rectilinear       sparse
TRIHEXAGON       tri-hexagon       triangles         sparse
QUARTERCUBIC     quartercubic      cubic             sparse
SUPPORTCUBIC     supportcubic      adaptivecubic     sparse
LATERALHONEYCOMB lateral-honeycomb honeycomb         sparse
LATERALLATTICE   lateral-lattice   grid              sparse
TPMSD            tpmsd             gyroid            sparse
TPMSFK           tpmsfk            gyroid            sparse
HILBERTCURVE     hilbertcurve      rectilinear       sparse,surface
OCTAGRAMSPIRAL   octagramspiral    archimedeanchords sparse,surface
"

WORK="$(mktemp -d "${TMPDIR:-/tmp}/orca-cli-infill.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK/datadir"

# Standalone presets: without "inherits" the CLI loads them as-is, with no preset bundle.
cat > "$WORK/machine.json" <<'EOF'
{
    "type": "machine",
    "from": "User",
    "name": "CLI infill test printer",
    "printable_area": ["0x0", "200x0", "200x200", "0x200"],
    "printable_height": "100",
    "layer_change_gcode": "G92 E0"
}
EOF

fails=0
fail() { echo "FAIL: $*"; fails=$((fails + 1)); }

# The G-code without its config block and the lines that differ between runs (generator line, label ids, M624).
normalize_body() {
    awk '
      /^; CONFIG_BLOCK_START/              { skip = 1; next }
      /^; CONFIG_BLOCK_END/                { skip = 0; next }
      skip                                 { next }
      /^; generated by /                   { next }
      /^; model label id: /                { next }
      /printing object, unique label id: / { next }
      /^M624 /                             { next }
      { sub(/\r$/, ""); print }' "$1"
}
config_block() {
    awk '/^; CONFIG_BLOCK_START/ { f = 1; next } /^; CONFIG_BLOCK_END/ { f = 0 } f { sub(/\r$/, ""); print }' "$1"
}

# run <option> <token>: slices the cube into $WORK/<option>-<token> once, keeping the log and the shell status there.
run() {
    local out="$WORK/$1-$2"
    [ -d "$out" ] && return
    mkdir -p "$out"
    cat > "$out/process.json" <<EOF
{
    "type": "process",
    "from": "User",
    "name": "CLI infill test process",
    "enable_support": "0",
    "enforce_support_layers": "0",
    "$1": "$2"
}
EOF
    timeout 300 "$BIN" --datadir "$WORK/datadir" --load-settings "$WORK/machine.json;$out/process.json" \
        --slice 0 --outputdir "$out" "$MODEL" > "$out/log" 2>&1
    echo $? > "$out/status"
}

# expect_warning <run dir> <option>
expect_warning() {
    "$PY" - "$1/result.json" "$2" <<'EOF' || fail "$1: result.json"
import json, sys

path, key = sys.argv[1:3]
try:
    with open(path) as f:
        result = json.load(f)
except (OSError, ValueError) as e:
    sys.exit("cannot read %s: %s" % (path, e))
warnings = result.get("warnings")
if not isinstance(warnings, list):
    sys.exit("warnings %r is not a list" % (warnings,))
found = [w for w in warnings if isinstance(w, dict) and w.get("class") == "infill_pattern_unavailable"]
if [w.get("key") for w in found] != [key]:
    sys.exit("infill_pattern_unavailable warnings %r, want one for %r" % (found, key))
EOF
}

# compare <option> <token> <fallback token>
compare() {
    local opt="$1" token="$2" fallback="$3"
    local got="$WORK/$opt-$token" want="$WORK/$opt-$fallback"
    echo "== $opt = $token slices as $opt = $fallback"
    run "$opt" "$token"
    run "$opt" "$fallback"
    [ "$(cat "$got/status")" -eq 0 ] || { fail "$opt=$token: shell status $(cat "$got/status")"; return; }
    [ "$(cat "$want/status")" -eq 0 ] || { fail "$opt=$fallback: shell status $(cat "$want/status")"; return; }
    [ -f "$got/plate_1.gcode" ] && [ -f "$want/plate_1.gcode" ] || { fail "$opt=$token: no G-code"; return; }
    grep -q "infill pattern is not included in this build" "$got/log" || fail "$opt=$token: console warning missing"
    expect_warning "$got" "$opt"
    cmp -s <(normalize_body "$got/plate_1.gcode") <(normalize_body "$want/plate_1.gcode") \
        || fail "$opt=$token: G-code differs from $opt=$fallback"
    local differences
    differences="$(diff <(config_block "$got/plate_1.gcode") <(config_block "$want/plate_1.gcode") | grep '^[<>]')"
    [ "$differences" = "$(printf '< ; %s = %s\n> ; %s = %s' "$opt" "$token" "$opt" "$fallback")" ] \
        || fail "$opt=$token: config blocks differ by: $differences"
}

compared=0
IFS=';' read -r -a left_out <<< "$LEFT_OUT"
for name in "${left_out[@]}"; do
    row="$(awk -v name="$name" '$1 == name' <<< "$PATTERNS")"
    # A left-out module of a pattern without an enum value is checked by its own tests.
    [ -n "$row" ] || { echo "SKIP: $name is not a built-in optional infill pattern"; continue; }
    read -r _ token fallback slots <<< "$row"
    compared=$((compared + 1))
    case ",$slots," in *,sparse,*)
        compare sparse_infill_pattern "$token" "$fallback" ;;
    esac
    case ",$slots," in *,surface,*)
        for opt in top_surface_pattern bottom_surface_pattern internal_solid_infill_pattern; do
            compare "$opt" "$token" "$fallback"
        done ;;
    esac
done

if [ "$fails" -ne 0 ]; then
    for log in "$WORK"/*/log; do
        echo "--- $log"
        tail -n 20 "$log"
    done
    exit 1
fi
[ "$compared" -gt 0 ] || { echo "SKIP: this build includes every built-in optional infill pattern"; exit 77; }
echo "PASS"
