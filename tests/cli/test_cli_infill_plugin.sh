#!/usr/bin/env bash
# End-to-end check of infill pattern plugins with the real orca-slicer binary.
#
# The sample plugin is found through ORCA_INFILL_PLUGIN_PATH or --infill-plugin-dir, and its pattern can then be
# named on the command line. Without the plugin the pattern is an invalid value. A project saved with the pattern
# loads where the plugin is missing, with the pattern substituted. Parameter warnings are printed and recorded. With
# the plugin loaded but not used, the G-code is the same as without it, config block included.
#
# usage: test_cli_infill_plugin.sh <orca-slicer binary> <python3> <directory of the sample plugin>
set -u

BIN="${1:-}"
PY="${2:-python3}"
PLUGIN_DIR="${3:-}"
# 77 is the test's SKIP_RETURN_CODE.
[ -x "$BIN" ] || { echo "SKIP: orca-slicer binary not found: $BIN"; exit 77; }
[ -d "$PLUGIN_DIR" ] || { echo "SKIP: sample plugin directory not found: $PLUGIN_DIR"; exit 77; }

# From src/libslic3r/Utils.hpp. main() returns them, so the shell sees them modulo 256.
CLI_INVALID_PARAMS=-2
TOKEN=org.orcaslicer.sample.lines
MODEL="$(cd "$(dirname "$0")/../data" && pwd)/20mm_cube.obj"

WORK="$(mktemp -d "${TMPDIR:-/tmp}/orca-cli-infill-plugin.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK/datadir"

# Standalone presets: without "inherits" the CLI loads them as-is, with no preset bundle.
cat > "$WORK/machine.json" <<'EOF'
{
    "type": "machine",
    "from": "User",
    "name": "CLI infill plugin test printer",
    "printable_area": ["0x0", "200x0", "200x200", "0x200"],
    "printable_height": "100",
    "layer_change_gcode": "G92 E0"
}
EOF
cat > "$WORK/process.json" <<'EOF'
{
    "type": "process",
    "from": "User",
    "name": "CLI infill plugin test process",
    "enable_support": "0",
    "enforce_support_layers": "0"
}
EOF

fails=0
fail() { echo "FAIL: $*"; fails=$((fails + 1)); }

# run <tag> [option...]: slices into $WORK/<tag>, keeping the log and the shell status there. Environment variables
# set by the caller are passed on.
run() {
    local out="$WORK/$1"; shift
    mkdir -p "$out"
    timeout 300 "$BIN" --datadir "$WORK/datadir" --load-settings "$WORK/machine.json;$WORK/process.json" \
        "$@" --outputdir "$out" > "$out/log" 2>&1
    echo $? > "$out/status"
}

# expect_status <tag> <cli code>
expect_status() {
    local got; got="$(cat "$WORK/$1/status")"
    [ "$got" -eq $(( $2 & 255 )) ] || fail "$1: shell status $got, want $(( $2 & 255 )) (code $2)"
}

# expect_sparse_infill <tag>
expect_sparse_infill() {
    grep -q -E '^(; FEATURE: |;TYPE:)Sparse infill' "$WORK/$1/plate_1.gcode" 2>/dev/null || fail "$1: no sparse infill in the G-code"
}

# The G-code without the lines that differ between runs (generator line, label ids, M624).
normalize() {
    awk '
      /^; generated by /                   { next }
      /^; model label id: /                { next }
      /printing object, unique label id: / { next }
      /^M624 /                             { next }
      { sub(/\r$/, ""); print }' "$1"
}

echo "== the plugin from ORCA_INFILL_PLUGIN_PATH"
ORCA_INFILL_PLUGIN_PATH="$PLUGIN_DIR" run env --sparse-infill-pattern="$TOKEN" --slice 0 "$MODEL"
expect_status env 0
expect_sparse_infill env

echo "== the plugin from --infill-plugin-dir"
run flag --infill-plugin-dir "$PLUGIN_DIR" --sparse-infill-pattern="$TOKEN" --slice 0 "$MODEL"
expect_status flag 0
expect_sparse_infill flag
cmp -s <(normalize "$WORK/env/plate_1.gcode") <(normalize "$WORK/flag/plate_1.gcode") || fail "flag: G-code differs from env"

echo "== parameter warnings reach standard error and result.json; loaded plugins reach the log file"
mkdir -p "$WORK/params"
run params --infill-plugin-dir "$PLUGIN_DIR" --sparse-infill-pattern="$TOKEN" \
    --infill-plugin-params="$TOKEN/spacing_scale=9" --debug 3 --logfile "$WORK/params/orca.log" --slice 0 "$MODEL"
expect_status params 0
grep -q "spacing_scale = 9 is outside" "$WORK/params/log" || fail "params: no parameter warning on standard error"
grep -q "Loaded infill plugin" "$WORK/params/orca.log" 2>/dev/null || fail "params: the loaded plugin is not in the log file"
"$PY" - "$WORK/params/result.json" <<'EOF2' || fail "params: result.json"
import json, sys

try:
    with open(sys.argv[1]) as f:
        result = json.load(f)
except (OSError, ValueError) as e:
    sys.exit("cannot read %s: %s" % (sys.argv[1], e))
warnings = [w for w in result.get("warnings", []) if isinstance(w, dict) and w.get("class") == "infill_plugin_params"]
if len(warnings) != 1 or "spacing_scale" not in warnings[0].get("text", ""):
    sys.exit("want one infill_plugin_params warning, got %r" % result.get("warnings"))
EOF2

echo "== without the plugin the pattern is an invalid value"
run missing --sparse-infill-pattern="$TOKEN" --slice 0 "$MODEL"
expect_status missing $CLI_INVALID_PARAMS
grep -q "Invalid value" "$WORK/missing/log" || fail "missing: no \"Invalid value\" message"

echo "== --no-infill-plugins"
ORCA_INFILL_PLUGIN_PATH="$PLUGIN_DIR" run disabled --no-infill-plugins --sparse-infill-pattern="$TOKEN" --slice 0 "$MODEL"
expect_status disabled $CLI_INVALID_PARAMS
grep -q "Invalid value" "$WORK/disabled/log" || fail "disabled: no \"Invalid value\" message"

echo "== a project with the pattern loads where the plugin is missing"
ORCA_INFILL_PLUGIN_PATH="$PLUGIN_DIR" run export --sparse-infill-pattern="$TOKEN" --slice 0 --export-3mf p.3mf "$MODEL"
expect_status export 0
if [ -f "$WORK/export/p.3mf" ]; then
    run reload --slice 0 "$WORK/export/p.3mf"
    expect_status reload 0
    "$PY" - "$WORK/reload/result.json" "$TOKEN" <<'EOF' || fail "reload: result.json"
import json, sys

path, token = sys.argv[1:3]
try:
    with open(path) as f:
        result = json.load(f)
except (OSError, ValueError) as e:
    sys.exit("cannot read %s: %s" % (path, e))
warnings = [w for w in result.get("warnings", []) if isinstance(w, dict) and w.get("class") == "config_value_substituted"]
if not any(w.get("old_value") == token for w in warnings):
    sys.exit("no config_value_substituted warning with old_value %r in %r" % (token, warnings))
EOF
else
    fail "export: no p.3mf"
fi

echo "== a loaded plugin does not change prints that do not use it"
run plain --slice 0 "$MODEL"
ORCA_INFILL_PLUGIN_PATH="$PLUGIN_DIR" run loaded --slice 0 "$MODEL"
expect_status plain 0
expect_status loaded 0
cmp -s <(normalize "$WORK/plain/plate_1.gcode") <(normalize "$WORK/loaded/plate_1.gcode") \
    || fail "loaded: G-code differs from a run without the plugin"

if [ "$fails" -ne 0 ]; then
    for log in "$WORK"/*/log; do
        echo "--- $log"
        tail -n 20 "$log"
    done
    exit 1
fi
echo "PASS"
