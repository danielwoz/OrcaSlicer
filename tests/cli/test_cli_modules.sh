#!/usr/bin/env bash
# End-to-end check of modules with the real orca-slicer binary.
#
# The sample modules are found through ORCA_MODULE_PATH or --module-dir, and their settings can then be given on the
# command line: infill walls add sparse infill, change at height inserts G-code at its height. With the modules loaded
# but not used, the G-code is the same as without them, config block included. A project saved with a module setting
# keeps it where the module is missing, with a warning, and gets it back once the module is installed again.
#
# usage: test_cli_modules.sh <orca-slicer binary> <python3> <directory of the sample modules>
set -u

BIN="${1:-}"
PY="${2:-python3}"
MODULE_DIR="${3:-}"
# 77 is the test's SKIP_RETURN_CODE.
[ -x "$BIN" ] || { echo "SKIP: orca-slicer binary not found: $BIN"; exit 77; }
[ -d "$MODULE_DIR" ] || { echo "SKIP: sample module directory not found: $MODULE_DIR"; exit 77; }

# From src/libslic3r/Utils.hpp. main() returns them, so the shell sees them modulo 256.
CLI_INVALID_PARAMS=-2
MODEL="$(cd "$(dirname "$0")/../data" && pwd)/20mm_cube.obj"

WORK="$(mktemp -d "${TMPDIR:-/tmp}/orca-cli-modules.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK/datadir"

# Standalone presets: without "inherits" the CLI loads them as-is, with no preset bundle.
cat > "$WORK/machine.json" <<'EOF'
{
    "type": "machine",
    "from": "User",
    "name": "CLI modules test printer",
    "printable_area": ["0x0", "200x0", "200x200", "0x200"],
    "printable_height": "100",
    "layer_change_gcode": "G92 E0"
}
EOF
cat > "$WORK/process.json" <<'EOF'
{
    "type": "process",
    "from": "User",
    "name": "CLI modules test process",
    "enable_support": "0",
    "enforce_support_layers": "0"
}
EOF

fails=0
fail() { echo "FAIL: $*"; fails=$((fails + 1)); }

# run <tag> [option...]: slices into $WORK/<tag>, keeping the log and the shell status there. Environment variables
# set by the caller are passed on.
run() {
    local out="$WORK/$1"; shift
    mkdir -p "$out"
    timeout 300 "$BIN" --datadir "$WORK/datadir" --load-settings "$WORK/machine.json;$WORK/process.json" \
        "$@" --outputdir "$out" > "$out/log" 2>&1
    echo $? > "$out/status"
}

# expect_status <tag> <cli code>
expect_status() {
    local got; got="$(cat "$WORK/$1/status")"
    [ "$got" -eq $(( $2 & 255 )) ] || fail "$1: shell status $got, want $(( $2 & 255 )) (code $2)"
}

# The G-code without the lines that differ between runs (generator line, label ids, M624).
normalize() {
    awk '
      /^; generated by /                   { next }
      /^; model label id: /                { next }
      /printing object, unique label id: / { next }
      /^M624 /                             { next }
      { sub(/\r$/, ""); print }' "$1"
}

# The normalized executable block, without the config block.
body() {
    normalize "$1" | sed -n '/^; EXECUTABLE_BLOCK_START/,/^; EXECUTABLE_BLOCK_END/p'
}

# sparse_extrusion <tag>: the filament extruded by the sparse infill moves, mm.
sparse_extrusion() {
    "$PY" - "$WORK/$1/plate_1.gcode" <<'EOF'
import sys

relative, e, sparse, total = False, 0., False, 0.
with open(sys.argv[1], errors="replace") as f:
    for line in f:
        if line.startswith(";TYPE:") or line.startswith("; FEATURE: "):
            sparse = line.split(":", 1)[1].strip() == "Sparse infill"
            continue
        words = line.split(";", 1)[0].split()
        if not words:
            continue
        if words[0] in ("M82", "M83"):
            relative = words[0] == "M83"
        elif words[0] in ("G0", "G1", "G2", "G3", "G92"):
            for word in words[1:]:
                if word[0] == "E":
                    value = float(word[1:])
                    if words[0] == "G92":
                        e = value
                    else:
                        delta = value if relative else value - e
                        e = e + value if relative else value
                        # Extruding moves only, not the unretractions.
                        if sparse and delta > 0 and any(w[0] in "XY" for w in words[1:]):
                            total += delta
print("%.5f" % total)
EOF
}

# expect_more_sparse_infill <tag> <tag of a run with less>
expect_more_sparse_infill() {
    local more less
    more="$(sparse_extrusion "$1")"; less="$(sparse_extrusion "$2")"
    awk -v a="$more" -v b="$less" 'BEGIN { exit !(a > b && b > 0) }' \
        || fail "$1: sparse infill $more mm, not more than the $less mm of $2"
}

# expect_config_line <tag> <line>
expect_config_line() {
    grep -q -x -F "$2" "$WORK/$1/plate_1.gcode" 2>/dev/null || fail "$1: no \"$2\" in the G-code"
}

echo "== modules from ORCA_MODULE_PATH; a project saved with a module setting"
ORCA_MODULE_PATH="$MODULE_DIR" run walls --infill-walls--loops=2 --slice 0 --export-3mf p.3mf "$MODEL"
expect_status walls 0
expect_config_line walls "; infill_walls__loops = 2"

echo "== modules from --module-dir"
run flag --module-dir "$MODULE_DIR" --infill-walls--loops=2 --slice 0 "$MODEL"
expect_status flag 0
cmp -s <(normalize "$WORK/walls/plate_1.gcode") <(normalize "$WORK/flag/plate_1.gcode") || fail "flag: G-code differs from walls"

echo "== loaded modules do not change prints that do not use them"
run plain --no-modules --slice 0 "$MODEL"
ORCA_MODULE_PATH="$MODULE_DIR" run loaded --slice 0 "$MODEL"
expect_status plain 0
expect_status loaded 0
cmp -s <(normalize "$WORK/plain/plate_1.gcode") <(normalize "$WORK/loaded/plate_1.gcode") \
    || fail "loaded: G-code differs from a run without modules"
expect_more_sparse_infill walls plain

echo "== change at height"
ORCA_MODULE_PATH="$MODULE_DIR" run change --change-at-z--height=5 --change-at-z--nozzle-temperature=215 --slice 0 "$MODEL"
expect_status change 0
"$PY" - "$WORK/change/plate_1.gcode" <<'EOF' || fail "change: inserted G-code"
import sys

with open(sys.argv[1], errors="replace") as f:
    lines = [line.rstrip("\r\n") for line in f]
at = [i for i, line in enumerate(lines) if line == "M104 S215"]
if len(at) != 1:
    sys.exit("want one M104 S215, got %d" % len(at))
if lines[at[0] - 1] != "; change_at_z: from 5.000 mm":
    sys.exit("M104 S215 follows %r" % lines[at[0] - 1])
# In the first layer at or above the height, after its layer change.
heights = [float(line[3:]) for line in lines[:at[0]] if line.startswith(";Z:")]
if len(heights) < 2 or heights[-1] < 5. - 1e-6 or heights[-2] >= 5. - 1e-6:
    sys.exit("inserted in the layer at %r, after the one at %r" % (heights[-1:], heights[-2:-1]))
EOF

echo "== the project without the modules keeps the setting, with a warning"
if [ -f "$WORK/walls/p.3mf" ]; then
    run kept --no-modules --slice 0 --export-3mf p.3mf "$WORK/walls/p.3mf"
    expect_status kept 0
    grep -q "infill_walls__loops" "$WORK/kept/plate_1.gcode" && fail "kept: the G-code names the setting of a missing module"
    "$PY" - "$WORK/kept/result.json" "$WORK/kept/p.3mf" <<'EOF' || fail "kept: result.json or the re-exported project"
import json, sys, zipfile

result_path, project_path = sys.argv[1:3]
try:
    with open(result_path) as f:
        result = json.load(f)
    with zipfile.ZipFile(project_path) as project:
        settings = json.loads(project.read("Metadata/project_settings.config"))
except (OSError, ValueError, KeyError, zipfile.BadZipFile) as e:
    sys.exit("cannot read %s or %s: %s" % (result_path, project_path, e))
warnings = [w for w in result.get("warnings", []) if isinstance(w, dict) and w.get("class") == "module_settings"]
if len(warnings) != 1 or "infill_walls__loops" not in warnings[0].get("text", ""):
    sys.exit("want one module_settings warning naming infill_walls__loops, got %r" % result.get("warnings"))
if settings.get("missing_module_options") != "infill_walls__loops = 2" or "infill_walls__loops" in settings:
    sys.exit("the re-exported project keeps %r" % {k: v for k, v in settings.items() if "__" in k or "module" in k})
EOF
    if [ -f "$WORK/kept/p.3mf" ]; then
        echo "== the module installed again restores the setting"
        ORCA_MODULE_PATH="$MODULE_DIR" run restored --slice 0 "$WORK/kept/p.3mf"
        expect_status restored 0
        expect_config_line restored "; infill_walls__loops = 2"
        cmp -s <(body "$WORK/walls/plate_1.gcode") <(body "$WORK/restored/plate_1.gcode") \
            || fail "restored: G-code body differs from walls"
    else
        fail "kept: no p.3mf"
    fi
else
    fail "walls: no p.3mf"
fi

echo "== without the modules their settings are invalid options"
ORCA_MODULE_PATH="$MODULE_DIR" run invalid --no-modules --infill-walls--loops=2 --slice 0 "$MODEL"
expect_status invalid $CLI_INVALID_PARAMS
grep -q "Invalid option --infill-walls--loops" "$WORK/invalid/log" || fail "invalid: no \"Invalid option\" message"

if [ "$fails" -ne 0 ]; then
    for log in "$WORK"/*/log; do
        echo "--- $log"
        tail -n 20 "$log"
    done
    exit 1
fi
echo "PASS"
